#!/usr/bin/env python3
"""Geometry versus retrieval, per model-layer (paper section "Two Geometries").

Reads (all local CSVs, no embeddings are loaded, CPU only):
  runs/active/resubmit/layer_diagnostics/geometry_per_layer.csv
      per model/layer/split/view label-free geometry (views raw, abtt_d10)
  runs/active/resubmit/results/phase_resubmit_results.csv
      per model/layer/method retrieval scores (test) and train-side selection scores

Writes:
  overleaf_drafts/tables/geometry_regimes.tex        (label tab:geometry_regimes)
  overleaf_drafts/tables/geometry_correlations.tex   (label tab:geometry_correlations)
  overleaf_drafts/figures/fig_geometry_vs_auroc.{pdf,png}
  overleaf_drafts/figures/fig_standardized_gap.{pdf,png}
  <facts_md> (default: z1_numbers.md next to this run, pass --facts_md) facts for prose drafters

Conventions: label-free geometry (top-PC share, effective rank) is read on the train
split; mean pairwise cosine is read on the test split (it is also reported on train in
the facts file); retrieval is always test. "raw" view = mean-pooled hidden states, no
correction. Top-PC share = first eigenvalue share of the centred (not L2-normalised)
embedding covariance (see scripts/resubmit/run_layer_geometry_diagnostics.py).
Standardized gap = baseline test gap (same_avg - diff_avg) / SD of all test pairwise
cosines at that layer (raw view).

Run from the repo root:
  python scripts/paper/reframe/geometry_vs_retrieval.py --facts_md <path>
Python 3.10, pandas / numpy / matplotlib / scipy only.
"""
