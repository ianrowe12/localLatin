def legend_handles(line=False):
    hs = []
    for mid, name, _, t5, col, mk in MODELS:
        hs.append(Line2D([0], [0], color=col if line else "none", marker=mk, markersize=5,
                         markerfacecolor=col if t5 else "white", markeredgecolor=col,
                         markeredgewidth=1.1, lw=1.2 if line else 0,
                         linestyle=("-" if t5 else "--") if line else "none", label=name))
    return hs


def fig_scatter(df, out):
    fig, axes = plt.subplots(1, 2, figsize=(6.3, 2.55), sharey=True)
    for ax, col, xl, pos in [(axes[0], "pc1_tr", "Top-PC share (centered, train)", (0.30, 0.42)),
                             (axes[1], "cos_te", "Mean pairwise cosine (test)", (0.03, 0.62))]:
        for mid, name, _, t5, c, mk in MODELS:
            s = df[df.m == name]
            ax.scatter(s[col], s.aucroc, marker=mk, s=22, linewidths=1.0,
                       facecolors=c if t5 else "white", edgecolors=c, zorder=3,
                       alpha=0.9 if t5 else 1.0)
