def load() -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    g = pd.read_csv(GEOM_CSV)
    r = pd.read_csv(RES_CSV)
    g["m"] = g["model"].map(DISP)
    r["m"] = r["model"].map(DISP)
    assert g["m"].notna().all() and r["m"].notna().all(), "unknown model id"

    def gv(split, view, cols):
        sub = g[(g.split == split) & (g.view == view)][["m", "layer"] + cols]
        return sub

    base = r[r.method == "baseline"][["m", "layer", "aucroc", "gap", "same_avg", "diff_avg",
                                      "dir_acc_at_1", "overall_assignment_acc",
                                      "train_aucroc", "train_dir_acc_at_1"]]
    df = base.merge(
        gv("test", "raw", ["anisotropy_mean_cosine", "cosine_std", "pc1_variance_ratio",
                           "effective_rank_entropy"]).rename(columns={
            "anisotropy_mean_cosine": "cos_te", "cosine_std": "cossd_te",
            "pc1_variance_ratio": "pc1_te", "effective_rank_entropy": "erank_te"}),
        on=["m", "layer"], validate="1:1")
    df = df.merge(
        gv("train", "raw", ["anisotropy_mean_cosine", "pc1_variance_ratio",
                            "effective_rank_entropy"]).rename(columns={
            "anisotropy_mean_cosine": "cos_tr", "pc1_variance_ratio": "pc1_tr",
            "effective_rank_entropy": "erank_tr"}),
        on=["m", "layer"], validate="1:1")
    df = df.merge(
        gv("train", "abtt_d10", ["pc1_variance_ratio", "effective_rank_entropy",
                                 "anisotropy_mean_cosine"]).rename(columns={
            "pc1_variance_ratio": "pc1_tr_abtt", "effective_rank_entropy": "erank_tr_abtt",
            "anisotropy_mean_cosine": "cos_tr_abtt"}),
        on=["m", "layer"], validate="1:1")
    for meth, tag in [("abtt_optimal", "abtt"), ("sif_only", "sif"),
                      ("abtt_fixed", "abttfix"), ("sif_abtt_optimal", "sifabtt")]:
        sub = r[r.method == meth][["m", "layer", "aucroc", "D", "dir_acc_at_1",
                                   "overall_assignment_acc"]].rename(columns={
            "aucroc": f"auc_{tag}", "D": f"D_{tag}", "dir_acc_at_1": f"dir1_{tag}",
            "overall_assignment_acc": f"assign_{tag}"})
        df = df.merge(sub, on=["m", "layer"], validate="1:1")
    df["sgap"] = df["gap"] / df["cossd_te"]
    df["abtt_gain"] = df["auc_abtt"] - df["aucroc"]
    df["is_t5"] = df["m"].isin(T5)
    df["m"] = pd.Categorical(df["m"], ORDER, ordered=True)
    df = df.sort_values(["m", "layer"]).reset_index(drop=True)
    df["depth"] = df["layer"] / df.groupby("m", observed=True)["layer"].transform("max")
    return df, g, r


def f3(x):
    return f"{x:.3f}"


def corr(x, y):
    return stats.pearsonr(x, y)[0], stats.spearmanr(x, y)[0]


def corr_rows(df, target):
    rows = []
    for col, label in STATS:
        out = {"stat": label, "col": col}
        for grp, sub in [("all", df), ("t5", df[df.is_t5]), ("nont5", df[~df.is_t5])]:
            out[f"{grp}_r"], out[f"{grp}_rho"] = corr(sub[col], sub[target])
            out[f"{grp}_n"] = len(sub)
        lomo = {m: stats.spearmanr(df[df.m != m][col], df[df.m != m][target])[0] for m in ORDER}
        out["lomo"] = lomo
        out["lomo_min"], out["lomo_max"] = min(lomo.values()), max(lomo.values())
        rows.append(out)
    return rows


def regime_rows(df):
    rows = []
    for m in ORDER:
        s = df[df.m == m]
        peak = s.loc[s.pc1_tr.idxmax()]
        worst = s.loc[s.aucroc.idxmin()]
        rows.append(dict(
            m=m, type=META[m][2], L=int(s.layer.max()),
            cos_min=s.cos_te.min(), cos_max=s.cos_te.max(),
            sd_min=s.cossd_te.min(), sd_max=s.cossd_te.max(),
            pc1_max=s.pc1_tr.max(), erank_min=s.erank_tr.min(),
            erank_min_layer=int(s.loc[s.erank_tr.idxmin(), "layer"]),
            peak_layer=int(peak.layer), auc_peak=peak.aucroc,
            auc_min=worst.aucroc, auc_min_layer=int(worst.layer)))
    return rows


