        rA_a = argmax_layer(rb, m, "abtt_optimal", "train_aucroc")
        rB_b = argmax_layer(rb, m, "baseline", "train_dir_acc_at_1")
        rB_a = argmax_layer(rb, m, "abtt_optimal", "train_dir_acc_at_1")
