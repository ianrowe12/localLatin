def parse_selected_layers():
    """Rows of selected_layers.tex: model -> {taskA_base, taskA_abtt, taskB_base, taskB_abtt}."""
    out = {}
    if not SEL_TEX.exists():
        return out
    for line in SEL_TEX.read_text().splitlines():
        cells = [c.strip() for c in line.rstrip("\\ ").split("&")]
        if len(cells) == 9 and cells[0] in ORDER and all(re.fullmatch(r"\d+", c) for c in cells[1:]):
            v = list(map(int, cells[1:]))
            out[cells[0]] = dict(A_base=v[0], A_sif=v[1], A_abtt=v[2], A_sifabtt=v[3],
                                 B_base=v[4], B_sif=v[5], B_abtt=v[6], B_sifabtt=v[7])
    return out


def argmax_layer(r, m, method, col):
    s = r[(r.m == m) & (r.method == method)].sort_values("layer")
    return int(s.loc[s[col].idxmax(), "layer"])  # first max = earliest layer on ties


