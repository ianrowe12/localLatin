import score_dataset2 as sd
from dataset2_parity import REFERENCE, REFERENCE_DISPLAY

METHOD_LABELS = {
    "baseline": "Base", "sif_only": "SIF", "abtt_optimal": "ABTT",
    "sif_abtt_fixed": "SIF+ABTT (fixed)", "sif_abtt_optimal": "SIF+ABTT",
    "whitening": "Whitening", "lasttok_abtt_optimal": "Last-token ABTT",
}


def tex(value):
    replacements = {"\\": r"\textbackslash{}", "_": r"\_", "&": r"\&",
                    "%": r"\%", "#": r"\#", "$": r"\$", "{": r"\{", "}": r"\}"}
    return "".join(replacements.get(c, c) for c in str(value))


def headline(accuracy, best, info):
    sub = accuracy[(accuracy["label_set"] == "agreed") & (accuracy["seen_group"] == "all")]

    def cell(model, method, metric):
        row = sub[(sub["model"] == model) & (sub["method"] == method)
                  & (sub["metric"] == metric)]
        if len(row) != 1:
            raise ValueError(f"Expected one agreed cell: {model}/{method}/{metric}")
        return row.iloc[0]

    def number(row, interval=False):
        if row["status"] != sd.SCORED:
            return "--"
        scale, digits = (100, 1) if row["metric"] == "acc@1" else (1, 3)
        if interval:
            return (r"{\scriptsize [" + f"{scale * row['ci_lo']:.{digits}f},"
                    + f"{scale * row['ci_hi']:.{digits}f}" + "]}")
        return f"{scale * row['value']:.{digits}f}"

    lines = [
        "% generated by score_dataset2.py render; do not edit",
        r"\begin{table*}[t]", r"\centering", r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}", r"\begin{tabular}{@{}llccccc@{}}", r"\toprule",
        r"& & & \multicolumn{2}{c}{Acc@1 (\%)} & \multicolumn{2}{c}{MRR} \\",
        r"\cmidrule(lr){4-5}\cmidrule(lr){6-7}",
        r"Model & Best (train) & $n$ (Base/Best) & Base & Best & Base & Best \\",
        r"\midrule",
    ]
    for selected in best.itertuples():
        name = selected.display
        cells = [cell(name, method, metric) for metric in ("acc@1", "mrr")
                 for method in ("baseline", selected.method)]
        sizes = f"{int(cells[0]['n'])}/{int(cells[1]['n'])}"
        lines.append(" & ".join([tex(name), tex(METHOD_LABELS[selected.method]), sizes]
                                + [number(row) for row in cells]) + r" \\")
        lines.append(" & & & " + " & ".join([number(row, True) for row in cells[:2]]
                                             + ["", ""]) + r" \\")
    ref = [cell(REFERENCE_DISPLAY, REFERENCE, metric) for metric in ("acc@1", "mrr")]
    lines += [
        r"\midrule",
        r"Char.\ n-grams & & " + str(int(ref[0]["n"])) + " & "
        + " & ".join(r"\multicolumn{2}{c}{" + number(row) + "}" for row in ref) + r" \\",
        r"& & & \multicolumn{2}{c}{" + number(ref[0], True)
        + r"} & \multicolumn{2}{c}{} \\",
        r"\bottomrule", r"\end{tabular}",
        r"\caption{Dataset 2, agreed labels. Base and the best post-processed method "
        r"at their benchmark-v1 train-selected layers and D. Best is selected by train "
        r"DirAcc@1, not by dataset-2 performance. Character 3--5-gram TF-IDF is fitted "
        r"on training witnesses only. Directory score is the maximum over its files. "
        r"Brackets: 95\% percentile bootstrap intervals over reviewed queries, "
        + f"{info['n_boot']:,}" + r" replicates. $n$ excludes unusable query vectors. "
        r"Intervals use the legacy score draws on identical cohorts; different exclusion "
        r"cohorts use a separate reference stream. Paired differences use shared resamples "
        r"on each contrast's common non-excluded queries.}",
        r"\label{tab:dataset2_headline}", r"\end{table*}",
    ]
    return "\n".join(lines) + "\n"


def differences(diffs, best, info):
    sub = diffs[(diffs["label_set"] == "agreed") & (diffs["seen_group"] == "all")]
    lines = [
        "% generated by score_dataset2.py render; do not edit",
        r"\begin{table*}[t]", r"\centering", r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}", r"\begin{tabular}{@{}lllcc@{}}", r"\toprule",
        r"Contrast & Model & Method & $\Delta$ Acc@1 (points) & $\Delta$ MRR \\",
        r"\midrule",
    ]
    for contrast, label in (("best_minus_baseline", "Best $-$ Base"),
                            ("model_minus_reference", "Best $-$ n-grams")):
        for selected in best.itertuples():
            cells = []
            for metric in ("acc@1", "mrr"):
                row = sub[(sub["contrast"] == contrast) & (sub["model"] == selected.display)
                          & (sub["method"] == selected.method) & (sub["metric"] == metric)]
                if len(row) != 1:
                    raise ValueError("Missing or duplicate paired table cell")
                row = row.iloc[0]
                scale, digits = (100, 1) if metric == "acc@1" else (1, 3)
                cells.append("--" if row["status"] != sd.SCORED else
                             f"{scale * row['estimate']:+.{digits}f} "
                             f"[{scale * row['ci_lo']:.{digits}f},"
                             f"{scale * row['ci_hi']:.{digits}f}]")
            lines.append(" & ".join([label, tex(selected.display),
                                     tex(METHOD_LABELS[selected.method]), *cells]) + r" \\")
        lines.append(r"\midrule")
    lines[-1] = r"\bottomrule"
    lines += [
        r"\end{tabular}",
        r"\caption{Dataset-2 paired differences on agreed labels at train-selected "
        r"configurations. Best is chosen on benchmark-v1 train only. Each contrast "
        r"uses the intersection of its non-excluded queries and the same query "
        r"resamples for both terms. 95\% percentile intervals, "
        + f"{info['n_boot']:,}" + r" replicates. All methods and label sets are in "
        r"the generated paired-differences CSV.}",
        r"\label{tab:dataset2_differences}", r"\end{table*}",
    ]
    return "\n".join(lines) + "\n"


def depth_figure(layers, accuracy, path):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D

    sys.path.insert(0, str(sd.REPO / "scripts" / "paper" / "reframe"))
    from paper_figures import style, TEXT_WIDTH_IN

    models = list(dict.fromkeys(layers["model"]))
    if not models:
        raise ValueError("No per-layer cells to plot")
    colours = ["#444444", "#009E73", "#0072B2", "#CC79A7", "#D55E00", "#E69F00", "#56B4E9"]
    styles = [":", "--", "-", "-.", "--", ":", "-."]
    with matplotlib.rc_context():
        style()
        fig, axes = plt.subplots(2, len(models), sharey="row", squeeze=False,
                                 figsize=(max(TEXT_WIDTH_IN, 1.05 * len(models)), 3.5))
        for col, model in enumerate(models):
            sub = layers[layers["model"] == model]
            for row, metric in enumerate(("acc@1", "mrr")):
                ax = axes[row, col]
                for method, colour, line in zip(sd.METHODS, colours, styles):
                    cells = sub[sub["method"] == method].sort_values("layer")
                    values = cells[metric].where(cells["status"] == sd.SCORED, np.nan)
                    if len(cells):
                        ax.plot(cells["layer"], values, color=colour, ls=line,
                                marker="o" if len(cells) <= 12 else None, markersize=2)
                ref = accuracy[(accuracy["model"] == REFERENCE_DISPLAY)
                               & (accuracy["label_set"] == "agreed")
                               & (accuracy["seen_group"] == "all") & (accuracy["metric"] == metric)]
                if len(ref) == 1 and ref.iloc[0]["status"] == sd.SCORED:
                    ax.axhline(ref.iloc[0]["value"], color="#888888", lw=0.8, ls="--")
                ax.set_ylim(0, 1.02)
                ax.set_xlim(sub["layer"].min() - 0.5, sub["layer"].max() + 0.5)
                ax.grid(True, axis="y")
                if col == 0:
                    ax.set_ylabel("Agreed " + ("acc@1" if row == 0 else "MRR"))
                if row == 0:
                    ax.set_title(sub["display"].iloc[0], pad=3)
                else:
                    ax.set_xlabel("Layer")
        handles = [Line2D([0], [0], color=c, ls=ls, label=METHOD_LABELS[m])
                   for m, c, ls in zip(sd.METHODS, colours, styles)]
        handles.append(Line2D([0], [0], color="#888888", ls="--", label="Char. n-grams"))
        fig.legend(handles=handles, loc="lower center", ncol=4, frameon=False,
                   bbox_to_anchor=(0.5, 0), fontsize=7)
        fig.subplots_adjust(left=0.08, right=0.99, top=0.92, bottom=0.28,
                            wspace=0.15, hspace=0.35)
        for suffix in (".pdf", ".png"):
            metadata = {"CreationDate": None} if suffix == ".pdf" else {}
            fig.savefig(path.with_suffix(suffix), bbox_inches="tight", pad_inches=0.02,
                        dpi=180, metadata=metadata)
        plt.close(fig)


def cmd_render(args):
    root = Path(args.out_dir)
    results = root / "results"
    accuracy = pd.concat([pd.read_csv(results / name) for name in
                          ("accuracy_long.csv", "reference_accuracy_long.csv")], ignore_index=True)
    best = pd.read_csv(results / "best_methods_train.csv")
    diffs = pd.read_csv(results / "paired_differences.csv")
    info = json.loads((results / "comparison_info.json").read_text())
    paper = root / "paper"
    paper.mkdir(parents=True, exist_ok=True)
    (paper / "headline_main.tex").write_text(headline(accuracy, best, info))
    (paper / "headline_ci_diffs.tex").write_text(differences(diffs, best, info))
    depth_figure(pd.read_csv(results / "per_layer.csv"), accuracy, paper / "fig_depth")
    (paper / "fig_depth.tex").write_text(
        "\\begin{figure*}[t]\n\\centering\n"
        "\\includegraphics[width=\\textwidth]{fig_depth.pdf}\n"
        "\\caption{Dataset-2 acc@1 and MRR over cached layers on agreed labels. "
        "Each optimal method uses D selected for that layer on benchmark-v1 train. "
        "No layer is selected on dataset 2. Gray dashed: character n-gram reference. "
        "Undefined whitening and unusable cells are gaps, not zeros.}\n"
        "\\label{fig:dataset2_depth}\n\\end{figure*}\n"
    )
    print(f"Wrote dataset-2 tables and depth figure -> {paper}")
